"""CI's lockfile comparison allows only Windows-only entries
(scripts/compare_lockfiles.py)."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from types import ModuleType

import pytest

ROOT = Path(__file__).resolve().parents[1]
H1 = "sha256:" + "1" * 64
H2 = "sha256:" + "2" * 64
H3 = "sha256:" + "3" * 64


@pytest.fixture(scope="module")
def lockcmp() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "compare_lockfiles", ROOT / "scripts" / "compare_lockfiles.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["compare_lockfiles"] = module
    spec.loader.exec_module(module)
    return module


def lock(*entries: str, python: str = "3.12") -> str:
    header = f"#\n# This file is autogenerated by pip-compile with Python {python}\n#\n"
    return header + "\n".join(entries) + "\n"


BOTO = (
    f"boto3==1.43.99 \\\n    --hash={H1} \\\n    --hash={H2}\n"
    "    # via -r requirements.in"
)
COLORAMA = f"colorama==0.4.6 \\\n    --hash={H3}\n    # via pytest"
PYWIN32 = f'pywin32==312 ; sys_platform == "win32" \\\n    --hash={H3}\n    # via mcp'


def test_identical_locks_agree(lockcmp: ModuleType) -> None:
    assert lockcmp.compare(lock(BOTO), lock(BOTO)) == []


def test_header_python_version_is_ignored(lockcmp: ModuleType) -> None:
    assert lockcmp.compare(lock(BOTO), lock(BOTO, python="3.13")) == []


def test_windows_only_entries_are_allowed(lockcmp: ModuleType) -> None:
    windows = lock(BOTO, COLORAMA, PYWIN32)
    linux = lock(BOTO)
    assert lockcmp.compare(windows, linux) == []


def test_a_dropped_ordinary_package_fails(lockcmp: ModuleType) -> None:
    extra = f"requests==2.32.3 \\\n    --hash={H3}"
    assert lockcmp.compare(lock(BOTO, extra), lock(BOTO)) == [
        "requests==2.32.3 is no longer resolved"
    ]


def test_a_new_package_fails(lockcmp: ModuleType) -> None:
    extra = f"requests==2.32.3 \\\n    --hash={H3}"
    assert lockcmp.compare(lock(BOTO), lock(BOTO, extra)) == [
        "requests==2.32.3 is missing from the lock"
    ]


def test_version_and_hash_drift_fail(lockcmp: ModuleType) -> None:
    newer = BOTO.replace("1.43.99", "1.44.0")
    assert lockcmp.compare(lock(BOTO), lock(newer)) == [
        "boto3: locked 1.43.99, resolves 1.44.0"
    ]
    rehashed = BOTO.replace(H2, H3)
    assert lockcmp.compare(lock(BOTO), lock(rehashed)) == [
        "boto3==1.43.99: hash set differs"
    ]


def test_extras_and_name_spelling_are_normalized(lockcmp: ModuleType) -> None:
    a = f"coverage[toml]==7.16.1 \\\n    --hash={H1}"
    b = f"Coverage==7.16.1 \\\n    --hash={H1}"
    assert lockcmp.compare(lock(a), lock(b)) == []


def test_real_lockfiles_parse(lockcmp: ModuleType) -> None:
    for name in ("requirements.lock", "requirements-agent.lock"):
        entries = lockcmp.parse_lockfile((ROOT / name).read_text(encoding="utf-8"))
        assert "boto3" in entries
        assert all(e.hashes for e in entries.values()), name
